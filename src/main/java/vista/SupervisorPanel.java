    private void modButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_modButtonActionPerformed
        // Obtener valores
        String nombre = nameText.getText().trim();
        String email = mailText.getText().trim();
        String password = ut.hashPass(new String(passText.getPassword()).trim());
        String id = idText.getText().trim();
        Object rolObj = rolCombo.getSelectedItem();

        // Validaciones
        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El nombre no puede estar vacío", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (rolObj == null) {
            JOptionPane.showMessageDialog(this, "Debes seleccionar un rol", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (email.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El email no puede estar vacío", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "La contraseña no puede estar vacía", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (id.isEmpty()) {
            JOptionPane.showMessageDialog(this, "ID de usuario no válido", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Ejecutar UPDATE
        ut.ejecutarUpdate(
                utilities.TipoConsulta.UPDATEUSER,
                nombre,
                rolObj.toString(),
                email,
                password,
                id
        );

        JOptionPane.showMessageDialog(this, "Usuario actualizado correctamente", "Éxito", JOptionPane.INFORMATION_MESSAGE);
        cargarDatos();
    }//GEN-LAST:event_modButtonActionPerformed

    private void altaButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_altaButtonActionPerformed
        // Obtener valores
        String nombre = nameAlta.getText().trim();
        String email = mailAlta.getText().trim();

        String password = new String(passAlta.getPassword()).trim();

        // Si confiAlta es JPasswordField, usa esto:
        String confiPass = new String(confAlta.getPassword()).trim();
        // Si confiAlta es JTextField, entonces sería:
        // String confiPass = confiAlta.getText().trim();

        Object rolObj = rolAlta.getSelectedItem();

        // Validaciones
        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El nombre no puede estar vacío", "Error", JOptionPane.ERROR_MESSAGE);
            nameAlta.requestFocus();
            return;
        }

        if (rolObj == null) {
            JOptionPane.showMessageDialog(this, "Debes seleccionar un rol", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (email.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El email no puede estar vacío", "Error", JOptionPane.ERROR_MESSAGE);
            mailAlta.requestFocus();
            return;
        }

        if (password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "La contraseña no puede estar vacía", "Error", JOptionPane.ERROR_MESSAGE);
            passAlta.requestFocus();
            return;
        }

        if (confiPass.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debes confirmar la contraseña", "Error", JOptionPane.ERROR_MESSAGE);
            confAlta.requestFocus();
            return;
        }

        if (!password.equals(confiPass)) {
            JOptionPane.showMessageDialog(this, "Las contraseñas no coinciden", "Error", JOptionPane.ERROR_MESSAGE);
            passAlta.requestFocus();
            return;
        }

        ut.ejecutarUpdate(
                utilities.TipoConsulta.ALTA,
                nombre,
                rolObj.toString(),
                email,
                ut.hashPass(password)
        );

        JOptionPane.showMessageDialog(this, "Usuario dado de alta correctamente", "Éxito", JOptionPane.INFORMATION_MESSAGE);
        limpiarCamposMod();
        cargarDatos();
    }//GEN-LAST:event_altaButtonActionPerformed

