    public void cargarDatos() {
        crs = ut.ejecutarConsulta(utilities.TipoConsulta.ROLES, 0);
        try {
            while (crs.next()) {
                rolAlta.addItem(crs.getString("descripcion"));
            }
        } catch (SQLException ex) {
            System.getLogger(SupervisorPanel.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }

        SwingUtilities.invokeLater(() -> {
            try {
                rs = ut.ejecutarConsulta(utilities.TipoConsulta.USUARIOS, 0);
                ut.cargarTabla(usersTable, rs);

                usersTable.getSelectionModel().addListSelectionListener(e -> {
                    if (!e.getValueIsAdjusting()) {
                        int fila = usersTable.getSelectedRow();
                        if (fila != -1) {
                            idText.setText(usersTable.getValueAt(fila, 0).toString());
                            nameText.setText(usersTable.getValueAt(fila, 1).toString());
                            rs = ut.ejecutarConsulta(utilities.TipoConsulta.ROLES, 0);
                            rolCombo.removeAllItems();
                            try {
                                while (rs.next()) {
                                    rolCombo.addItem(rs.getString("descripcion"));
                                }
                            } catch (SQLException ex) {
                                System.getLogger(SupervisorPanel.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
                            }
                            rolCombo.setSelectedItem(usersTable.getValueAt(fila, 2).toString());
                            mailText.setText(usersTable.getValueAt(fila, 3).toString());
                            passText.setText(usersTable.getValueAt(fila, 4).toString());
                        }
                    }
                });
                // Actualizamos el sorter con el nuevo modelo en caso de recarga
                //sorter.setModel((DefaultTableModel) usersTable.getModel());

            } catch (SQLException ex) {
                System.out.println(ex.getMessage());
            }
        });

    }

